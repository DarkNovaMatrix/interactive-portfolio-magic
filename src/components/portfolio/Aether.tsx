import { useCallback, useEffect, useRef, useState } from "react";
import { AnimatePresence, motion, useMotionValue, useSpring } from "framer-motion";
import { useNavigate, useRouterState } from "@tanstack/react-router";
import { useServerFn } from "@tanstack/react-start";
import { useAether, type Form } from "@/lib/aether-state";
import { useTheme } from "@/lib/theme";
import { useAetherSTT, useAetherTTS } from "@/lib/aether-voice";
import { aetherSpeak } from "@/lib/aether.functions";
import { AetherForm3D } from "./AetherForm3D";
import { Mic, MicOff, Volume2, VolumeX } from "lucide-react";

/**
 * AETHER — an autonomous shape-shifting companion.
 * - Roams the viewport, tracks the cursor, morphs form by emotion.
 * - Speaks in-character lines generated by Gemini via Lovable AI.
 * - Optional voice: browser TTS (with emotion-mapped prosody) + mic input.
 * - Escorts you between routes with a particle trail.
 */
export function Aether() {
  const {
    state, say, shift, feel, nudge,
    noteSection, noteInteraction,
    startEscort, advanceEscort, endEscort,
  } = useAether();
  const { theme, toggle } = useTheme();
  const navigate = useNavigate();
  const routerState = useRouterState();
  const speak = useServerFn(aetherSpeak);

  const tts = useAetherTTS();
  const onHeard = useCallback((t: string) => {
    // Push what the user said back into the LLM as a trigger
    void llmSpeak(`user said aloud: "${t}"`);
    nudge({ curiosity: 8, happiness: 3, energy: 3 });
    feel("surprised");
  }, []);
  const stt = useAetherSTT(onHeard);

  const [mounted, setMounted] = useState(false);
  const [dragging, setDragging] = useState(false);
  const [hovered, setHovered] = useState(false);
  const [showChrome, setShowChrome] = useState(false);

  const rx = useMotionValue(0);
  const ry = useMotionValue(0);
  // Snap-and-hold: high stiffness + heavy mass = fast lift, planted landing.
  const sx = useSpring(rx, { stiffness: 210, damping: 26, mass: 1.6 });
  const sy = useSpring(ry, { stiffness: 210, damping: 26, mass: 1.6 });

  const cursor = useRef({ x: 0, y: 0, moving: false, movedAt: 0 });
  const target = useRef({ x: 0, y: 0 });
  const lastSpeakAt = useRef(0);
  const inFlight = useRef(false);
  const stateRef = useRef(state);
  stateRef.current = state;

  // LLM speak, throttled to avoid spam and cost
  const llmSpeak = useCallback(
    async (trigger: string, opts: { section?: string; force?: boolean } = {}) => {
      const now = Date.now();
      if (!opts.force && now - lastSpeakAt.current < 6000) return;
      if (inFlight.current) return;
      inFlight.current = true;
      lastSpeakAt.current = now;
      try {
        const s = stateRef.current;
        const res = await speak({
          data: {
            emotion: s.emotion,
            form: s.form,
            trigger,
            route: window.location.pathname,
            section: opts.section,
            visits: s.memory.visits,
            sectionsSeen: s.memory.sectionsSeen,
            recent: s.memory.recentLines.slice(-4),
          },
        });
        const text = res?.text?.trim();
        if (text) {
          say(text, 5200);
          if (tts.enabled) tts.speak(text, { emotion: s.emotion });
        }
      } catch (err) {
        console.warn("aether speak failed", err);
      } finally {
        inFlight.current = false;
      }
    },
    [speak, say, tts],
  );

  useEffect(() => {
    setMounted(true);
    const w = window.innerWidth;
    const h = window.innerHeight;
    rx.set(w - 140);
    ry.set(h - 160);
    target.current = { x: w - 140, y: h - 160 };
    setTimeout(() => llmSpeak("greet", { force: true }), 900);
    setTimeout(() => setShowChrome(true), 1600);
  }, []);

  // cursor tracking
  useEffect(() => {
    function onMove(e: MouseEvent) {
      cursor.current = { x: e.clientX, y: e.clientY, moving: true, movedAt: Date.now() };
      noteInteraction();
      const t = e.target as HTMLElement;
      const el = t.closest<HTMLElement>("[data-aether-hint]");
      if (el?.dataset.aetherHint) {
        say(el.dataset.aetherHint, 3000);
        nudge({ curiosity: 2 });
      }
    }
    window.addEventListener("mousemove", onMove);
    return () => window.removeEventListener("mousemove", onMove);
  }, [noteInteraction, nudge, say]);

  // scroll
  useEffect(() => {
    let last = window.scrollY;
    let lastT = Date.now();
    function onScroll() {
      const dy = Math.abs(window.scrollY - last);
      const dt = Math.max(1, Date.now() - lastT);
      const v = dy / dt;
      last = window.scrollY;
      lastT = Date.now();
      noteInteraction();
      if (v > 3) nudge({ playfulness: 1, energy: 1 });
    }
    window.addEventListener("scroll", onScroll, { passive: true });
    return () => window.removeEventListener("scroll", onScroll);
  }, [noteInteraction, nudge]);

  // section watchers
  useEffect(() => {
    const sections = Array.from(document.querySelectorAll<HTMLElement>("[data-aether-section]"));
    if (!sections.length) return;
    const io = new IntersectionObserver(
      (entries) => {
        for (const e of entries) {
          if (e.isIntersecting && e.intersectionRatio > 0.4) {
            const name = (e.target as HTMLElement).dataset.aetherSection!;
            if (!stateRef.current.memory.sectionsSeen.includes(name)) {
              noteSection(name);
              nudge({ curiosity: 4, happiness: 2 });
              shift(name.toLowerCase().includes("work") ? "cube" : "constellation");
              void llmSpeak(`arrived at new section "${name}"`, { section: name });
            }
          }
        }
      },
      { threshold: [0.4, 0.7] },
    );
    sections.forEach((s) => io.observe(s));
    return () => io.disconnect();
  }, [llmSpeak, noteSection, nudge, shift, routerState.location.pathname]);

  // roaming — suspended during escort
  useEffect(() => {
    const iv = setInterval(() => {
      if (dragging || state.escort) return;
      const w = window.innerWidth;
      const h = window.innerHeight;
      const emo = state.emotion;
      const c = cursor.current;
      const cursorFresh = Date.now() - c.movedAt < 1500;

      let tx: number;
      let ty: number;

      if (emo === "sleepy") {
        tx = w - 130 + (Math.random() - 0.5) * 20;
        ty = h - 130 + (Math.random() - 0.5) * 20;
      } else if (emo === "playful" && cursorFresh) {
        const angle = Math.random() * Math.PI * 2;
        tx = c.x + Math.cos(angle) * 90;
        ty = c.y + Math.sin(angle) * 90;
      } else if (emo === "excited") {
        tx = Math.random() * (w - 160) + 80;
        ty = Math.random() * (h * 0.6) + 80;
      } else if (emo === "focused" && cursorFresh) {
        tx = c.x + 70;
        ty = Math.max(60, c.y - 100);
      } else {
        tx = Math.random() * (w - 200) + 100;
        ty = Math.random() * (h - 240) + 120;
      }

      tx = Math.max(60, Math.min(w - 80, tx));
      ty = Math.max(60, Math.min(h - 80, ty));
      target.current = { x: tx, y: ty };
      rx.set(tx);
      ry.set(ty);
    }, 3800);
    return () => clearInterval(iv);
  }, [dragging, rx, ry, state.emotion, state.escort]);

  // escort choreography
  useEffect(() => {
    if (!state.escort) return;
    const e = state.escort;
    if (e.phase === "toLink") {
      shift("arrow");
      feel("excited");
      rx.set(e.toX);
      ry.set(e.toY);
      const t = setTimeout(() => {
        advanceEscort("toTop");
        navigate({ to: e.toPath as any });
      }, 850);
      return () => clearTimeout(t);
    }
    if (e.phase === "toTop") {
      // fly to hero area on the new page
      const t = setTimeout(() => {
        const w = window.innerWidth;
        const h = window.innerHeight;
        rx.set(w * 0.72);
        ry.set(h * 0.32);
        window.scrollTo({ top: 0, behavior: "smooth" });
      }, 200);
      const done = setTimeout(() => {
        endEscort();
        shift("orb");
        feel("curious");
        void llmSpeak(`escort complete to ${e.toPath}`, { force: true });
      }, 1400);
      return () => {
        clearTimeout(t);
        clearTimeout(done);
      };
    }
  }, [state.escort, rx, ry, shift, feel, advanceEscort, endEscort, navigate, llmSpeak]);

  // publish live position for the particle trail
  useEffect(() => {
    let raf = 0;
    const push = () => {
      (window as any).__aetherPos = {
        x: sx.get(),
        y: sy.get(),
        escorting: !!stateRef.current.escort,
      };
      raf = requestAnimationFrame(push);
    };
    raf = requestAnimationFrame(push);
    return () => cancelAnimationFrame(raf);
  }, [sx, sy]);

  // click handler
  function onClick() {
    noteInteraction();
    nudge({ happiness: 6, playfulness: 4, energy: 5 });
    feel("excited");
    const forms: Form[] = ["orb", "cube", "blob", "constellation", "arrow", "spark"];
    shift(forms[Math.floor(Math.random() * forms.length)]);
    void llmSpeak("user poked me", { force: false });
  }

  if (!mounted) return null;

  return (
    <>
      <motion.div
        style={{ x: sx, y: sy, scale: state.scale }}
        className="fixed left-0 top-0 z-[95] pointer-events-none"
      >
        {/* speech */}
        <AnimatePresence>
          {state.message && (
            <motion.div
              initial={{ opacity: 0, y: 6, scale: 0.9 }}
              animate={{ opacity: 1, y: 0, scale: 1 }}
              exit={{ opacity: 0, y: 6, scale: 0.9 }}
              className="pointer-events-none absolute -translate-x-1/2 -translate-y-full left-1/2 -top-6 w-[240px]"
            >
              <div className="serif italic text-base bg-ink text-paper px-3 py-2 rounded-xl leading-snug shadow-2xl text-center">
                {state.message}
                <div className="text-[10px] not-italic tracking-widest uppercase opacity-50 mt-1 font-sans">
                  aether · {state.emotion}{tts.speaking ? " · speaking" : ""}
                </div>
              </div>
            </motion.div>
          )}
        </AnimatePresence>

        {/* body */}
        <motion.div
          drag
          dragMomentum={false}
          onDragStart={() => setDragging(true)}
          onDragEnd={(_, info) => {
            setDragging(false);
            rx.set(rx.get() + info.offset.x);
            ry.set(ry.get() + info.offset.y);
          }}
          onClick={onClick}
          onDoubleClick={() => {
            toggle();
            void llmSpeak(theme === "dark" ? "user turned lights on" : "user dimmed the room");
          }}
          onHoverStart={() => setHovered(true)}
          onHoverEnd={() => setHovered(false)}
          whileHover={{ scale: 1.08 }}
          className="pointer-events-auto -translate-x-1/2 -translate-y-1/2 cursor-grab active:cursor-grabbing"
          aria-label="AETHER — autonomous companion"
        >
          <AetherForm3D form={state.form} emotion={state.emotion} active={hovered || dragging || !!state.escort} />
        </motion.div>
      </motion.div>

      {/* Voice controls — fixed to bottom-right, independent of Aether's roam */}
      <AnimatePresence>
        {showChrome && (
          <motion.div
            initial={{ opacity: 0, y: 10 }}
            animate={{ opacity: 1, y: 0 }}
            exit={{ opacity: 0, y: 10 }}
            className="fixed bottom-5 right-5 z-[96] flex gap-2"
          >
            <button
              onClick={() => {
                tts.toggle();
                if (!tts.enabled) void llmSpeak("user gave me a voice", { force: true });
              }}
              title={tts.enabled ? "Mute AETHER" : "Give AETHER a voice"}
              className="rounded-full bg-ink text-paper w-10 h-10 flex items-center justify-center shadow-lg hover:scale-110 transition"
              aria-label={tts.enabled ? "Mute AETHER" : "Enable AETHER voice"}
            >
              {tts.enabled ? <Volume2 size={16} /> : <VolumeX size={16} />}
            </button>
            {stt.supported && (
              <button
                onClick={() => (stt.listening ? stt.stop() : stt.start())}
                title={stt.listening ? "Stop listening" : "Talk to AETHER"}
                className={`rounded-full w-10 h-10 flex items-center justify-center shadow-lg hover:scale-110 transition ${
                  stt.listening ? "bg-accent text-ink animate-pulse" : "bg-ink text-paper"
                }`}
                aria-label={stt.listening ? "Stop listening" : "Talk to AETHER"}
              >
                {stt.listening ? <MicOff size={16} /> : <Mic size={16} />}
              </button>
            )}
          </motion.div>
        )}
      </AnimatePresence>
    </>
  );
}

/** Hook a nav link/button up to Aether escort. Renders a <button> that
 * flies AETHER to the link, then navigates, then drops it near the hero. */
export function useAetherEscort() {
  const { startEscort } = useAether();
  const navigate = useNavigate();
  return useCallback(
    (path: string, ev?: React.MouseEvent<HTMLElement>) => {
      if (ev) ev.preventDefault();
      const rect = ev?.currentTarget?.getBoundingClientRect();
      const x = rect ? rect.left + rect.width / 2 : window.innerWidth / 2;
      const y = rect ? rect.top + rect.height / 2 + 24 : 60;
      startEscort({ toPath: path, toX: x, toY: y, phase: "toLink" });
      // safety net — if state doesn't advance for some reason, still navigate
      setTimeout(() => {
        if (window.location.pathname !== path) navigate({ to: path as any });
      }, 1400);
    },
    [navigate, startEscort],
  );
}
